/* Offline scenery generator (build-time tool; not part of the app or its dependencies).
 *
 * Paints the hero, sidebar and backdrop art in headless Chrome with canvas "watercolour/gouache" simulation
 * (see paint.js / scenes.js), exports WebP files into src/assets/scenery/ and writes src/styles/scenery-art.css.
 *
 * Usage (from frontend/):
 *   NODE_PATH=E:/UserData/.claude/skills/ui-acceptance/scripts/node_modules node scripts/paint-scenery/generate.cjs [meadow sky forest sidebar backdrop]
 * Playwright is only used here; it is deliberately not a frontend dependency. Needs an installed Chrome.
 */
const fs = require("fs");
const path = require("path");
const { chromium } = require("playwright");

const root = path.resolve(__dirname, "../..");
const outDir = path.join(root, "src/assets/scenery");
const cssFile = path.join(root, "src/styles/scenery-art.css");
const which = process.argv.slice(2);

const pct = (v) => `${(v * 100).toFixed(3)}%`;

(async () => {
  fs.mkdirSync(outDir, { recursive: true });
  const browser = await chromium.launch({ channel: "chrome" });
  const page = await browser.newPage();
  page.on("pageerror", (e) => console.error("page error:", e.message));
  await page.setContent("<!doctype html><body></body>");
  await page.addScriptTag({ path: path.join(__dirname, "paint.js") });
  await page.addScriptTag({ path: path.join(__dirname, "scenes.js") });
  const items = await page.evaluate((w) => window.renderAll(w), which);
  await browser.close();

  let total = 0;
  const meta = {};
  const size = {};
  for (const it of items) {
    const buf = Buffer.from(it.dataUrl.split(",")[1], "base64");
    fs.writeFileSync(path.join(outDir, `${it.name}.webp`), buf);
    total += buf.length;
    meta[it.name] = it.rect;
    size[it.name] = [it.w, it.h];
    console.log(`${it.name}.webp  ${it.w}x${it.h}  ${(buf.length / 1024).toFixed(1)} KB`);
  }
  console.log(`total ${(total / 1024).toFixed(0)} KB`);
  if (which.length) return; // a partial run does not rewrite the CSS manifest

  const rule = (sel, name, extra = "") => {
    const r = meta[name];
    const box = r ? `  left: ${pct(r.left)};\n  top: ${pct(r.top)};\n  width: ${pct(r.width)};\n  height: ${pct(r.height)};\n` : "";
    return `${sel} {\n  background-image: url("../assets/scenery/${name}.webp");\n${box}${extra}}\n`;
  };
  let css = "/* Generated by scripts/paint-scenery/generate.cjs. Do not edit by hand; regenerate instead. */\n\n";
  for (const [mode, scene] of [["rewrite", "meadow"], ["generate", "sky"], ["novel", "forest"]]) {
    css += `.scene-${mode} {\n  -webkit-mask-image: url("../assets/scenery/${scene}-bg.webp");\n  mask-image: url("../assets/scenery/${scene}-bg.webp");\n}\n\n`;
    css += rule(`.scene-${mode} .l-bg`, `${scene}-bg`).replace(/  left:[^\n]*\n  top:[^\n]*\n  width:[^\n]*\n  height:[^\n]*\n/, "") + "\n";
    for (const [cls, part] of [["l-clouds-far", "clouds-far"], ["l-clouds-near", "clouds-near"], ["l-smoke", "smoke"], ["l-light", "light"], ["l-grass", "grass"], ["l-windmill", "windmill"], ["l-kite", "kite"]]) {
      if (meta[`${scene}-${part}`]) css += rule(`.scene-${mode} .${cls}`, `${scene}-${part}`) + "\n";
    }
  }
  for (const [cls, name] of [["sidebar-scene-art", "sidebar-edge"], ["sidebar-scene-grass", "sidebar-grass"], ["sidebar-scene-leaves", "sidebar-leaves"], ["sidebar-scene-glow", "sidebar-glints"], ["backdrop-meadow", "page-foot"]]) {
    css += `.${cls} {\n  background-image: url("../assets/scenery/${name}.webp");\n}\n\n`;
  }
  fs.writeFileSync(cssFile, css.replace(/\n+$/, "\n"));
  console.log("wrote", path.relative(root, cssFile));
})();
